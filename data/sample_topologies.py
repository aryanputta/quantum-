# ---------------------------------------------------------------------------
# Registry for easy lookup by name
# ---------------------------------------------------------------------------

TOPOLOGIES = {
    "ring_mesh_10": RING_MESH_10,
    "isp_15":       ISP_15,
    "random_20":    RANDOM_20,
}

TOPOLOGY_NAMES = list(TOPOLOGIES.keys())


def get_topology(name: str) -> dict:
    """Return a topology dict by name.

    Parameters
    ----------
    name : str
        One of ``'ring_mesh_10'``, ``'isp_15'``, or ``'random_20'``.

    Returns
    -------
    dict
        Topology dict with keys ``'nodes'`` and ``'edges'``.

    Raises
    ------
    KeyError
        If *name* is not a recognised topology.
    """
    if name not in TOPOLOGIES:
        raise KeyError(
            f"Unknown topology '{name}'. Available: {TOPOLOGY_NAMES}"
        )
    return TOPOLOGIES[name]
